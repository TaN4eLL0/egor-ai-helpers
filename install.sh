#!/usr/bin/env bash
# install.sh — idempotent installer for egor-ai-helpers
#
# Splices claude/rules/*.md (concatenated in filename order) into
# ~/.claude/CLAUDE.md between the egor-ai markers. A rule file that starts
# with YAML frontmatter containing `paths:` is path-scoped instead: it is
# copied to ~/.claude/rules/egor-ai-<name>.md and loads only when Claude
# reads a matching file. Also copies claude/agents,
# claude/commands and claude/hooks into ~/.claude/, registers the SessionStart
# hooks and the repo git hooks, and records the checkout path in
# ~/.config/egor-ai-helpers/install.conf. Hooks listed in claude/hooks/hooks.json
# are registered in ~/.claude/settings.json; claude/skills/*/ go to ~/.claude/skills/.
#
# Safe to re-run: it only ever rewrites its own marker block and never pulls
# git on its own.
#
# Usage:
#   ./install.sh              # install / refresh
#   ./install.sh --dry-run    # print the block that would be written
#   ./install.sh --check      # exit 0 if ~/.claude/CLAUDE.md matches claude/rules/, 1 if stale
#   ./install.sh --uninstall  # remove the managed block and installed payload
#   ./install.sh --quiet      # install / refresh without output (used by the git hooks)

set -euo pipefail

REPO_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
RULES_DIR="${REPO_ROOT}/claude/rules"
CLAUDE_DIR="${HOME}/.claude"
CLAUDE_MD="${CLAUDE_DIR}/CLAUDE.md"
CONFIG_DIR="${HOME}/.config/egor-ai-helpers"
MARKER_START='<!-- egor-ai:start -->'
MARKER_END='<!-- egor-ai:end -->'
USER_RULES_DIR="${CLAUDE_DIR}/rules"

is_scoped() { head -n 1 "$1" | grep -q '^---$' && sed -n '2,/^---$/p' "$1" | grep -q '^paths:'; }
scoped_target() { printf '%s/egor-ai-%s' "$USER_RULES_DIR" "$(basename "$1")"; }
render() { sed -e "s|{{REPO_ROOT}}|${REPO_ROOT}|g" "$1"; }

DRY_RUN=0
UNINSTALL=0
CHECK=0
QUIET=0
for arg in "$@"; do
    case "$arg" in
        --dry-run)   DRY_RUN=1 ;;
        --uninstall) UNINSTALL=1 ;;
        --check)     CHECK=1 ;;
        --quiet)     QUIET=1 ;;
        -h|--help)   grep -E '^# ' "$0" | sed 's/^# \?//'; exit 0 ;;
        *) echo "Unknown arg: $arg (use --help)" >&2; exit 1 ;;
    esac
done

say()  { printf '  %s\n' "$*"; }
ok()   { printf '\033[32m✓\033[0m %s\n' "$*"; }
warn() { printf '\033[33m⚠\033[0m %s\n' "$*"; }
err()  { printf '\033[31m✗\033[0m %s\n' "$*" >&2; }

build_block() {
    printf '%s\n' "$MARKER_START"
    printf '<!-- Generated by %s/install.sh — do not edit here, edit claude/rules/ -->\n\n' "$REPO_ROOT"
    local first=1
    for f in "${RULES_DIR}"/*.md; do
        [[ -f "$f" ]] || continue
        is_scoped "$f" && continue
        [[ "$first" -eq 1 ]] || printf '\n'
        first=0
        render "$f"
    done
    printf '\n%s\n' "$MARKER_END"
}

splice() {
    BLOCK_FILE="$1" CLAUDE_MD_PATH="$CLAUDE_MD" python3 - <<'PY'
import os, pathlib, re

target = pathlib.Path(os.environ["CLAUDE_MD_PATH"])
block = pathlib.Path(os.environ["BLOCK_FILE"]).read_text().rstrip() + "\n"
text = target.read_text() if target.exists() else ""

pattern = re.compile(
    r"<!-- egor-ai:start -->.*?<!-- egor-ai:end -->\n?",
    flags=re.DOTALL,
)
if pattern.search(text):
    new, action = pattern.sub(block, text), "updated"
else:
    sep = "" if not text else ("\n" if text.endswith("\n") else "\n\n")
    new, action = text + sep + "\n" + block, "appended"

if new != text:
    target.write_text(new)
    print(f"  {action} managed block in {target}")
else:
    print(f"  {target} already up to date")
PY
}

SETTINGS_JSON="${CLAUDE_DIR}/settings.json"
HOOKS_MANIFEST="${REPO_ROOT}/claude/hooks/hooks.json"

sync_hooks() {
    ACTION="$1" MANIFEST="$HOOKS_MANIFEST" HOOKS_DIR="${CLAUDE_DIR}/hooks" SETTINGS="$SETTINGS_JSON" python3 - <<'PY'
import json, os, pathlib

settings = pathlib.Path(os.environ["SETTINGS"])
hooks_dir = os.environ["HOOKS_DIR"]
manifest = json.loads(pathlib.Path(os.environ["MANIFEST"]).read_text())
raw = settings.read_text() if settings.exists() else "{}"
data = json.loads(raw or "{}")
hooks = data.setdefault("hooks", {})

def ours(h):
    return os.path.dirname(h.get("command", "")) == hooks_dir and os.path.basename(h.get("command", "")).startswith("egor-ai-")

for event, groups in list(hooks.items()):
    for g in groups:
        g["hooks"] = [h for h in g.get("hooks", []) if not ours(h)]
    hooks[event] = [g for g in groups if g.get("hooks")]
    if not hooks[event]:
        del hooks[event]

if os.environ["ACTION"] == "register":
    for event, entries in manifest.items():
        for e in entries:
            group = {"hooks": [{"type": "command", "command": f"{hooks_dir}/{e['command']}"}]}
            if e.get("matcher"):
                group["matcher"] = e["matcher"]
            hooks.setdefault(event, []).append(group)
    print("  hooks registered: " + ", ".join(f"{ev} x{len(en)}" for ev, en in manifest.items()))
else:
    print("  hooks removed from settings.json")

if not hooks:
    data.pop("hooks", None)
settings.write_text(json.dumps(data, indent=2, ensure_ascii=False) + ("\n" if raw.endswith("\n") else ""))
PY
}

if [[ "$CHECK" -eq 1 ]]; then
    CHECK_BLOCK="$(mktemp)"
    trap 'rm -f "$CHECK_BLOCK"' EXIT
    build_block > "$CHECK_BLOCK"
    if BLOCK_FILE="$CHECK_BLOCK" CLAUDE_MD_PATH="$CLAUDE_MD" python3 - <<'PY'
import os, pathlib, re, sys

target = pathlib.Path(os.environ["CLAUDE_MD_PATH"])
block = pathlib.Path(os.environ["BLOCK_FILE"]).read_text().rstrip()
text = target.read_text() if target.exists() else ""
found = re.search(r"<!-- egor-ai:start -->.*?<!-- egor-ai:end -->", text, flags=re.DOTALL)
sys.exit(0 if found and found.group(0).rstrip() == block else 1)
PY
    then
        for f in "${RULES_DIR}"/*.md; do
            is_scoped "$f" || continue
            cmp -s <(render "$f") "$(scoped_target "$f")" || exit 1
        done
        exit 0
    fi
    exit 1
fi

[[ "$QUIET" -eq 1 ]] && exec >/dev/null

if [[ "$UNINSTALL" -eq 1 ]]; then
    echo
    say "Removing managed block from ${CLAUDE_MD}..."
    if [[ -f "$CLAUDE_MD" ]]; then
        CLAUDE_MD_PATH="$CLAUDE_MD" python3 - <<'PY'
import os, pathlib, re
p = pathlib.Path(os.environ["CLAUDE_MD_PATH"])
text = p.read_text()
new = re.sub(r"\n*<!-- egor-ai:start -->.*?<!-- egor-ai:end -->\n*", "\n", text, flags=re.DOTALL)
if new != text:
    p.write_text(new)
    print("  removed managed block")
else:
    print("  no managed block found")
PY
    else
        say "  ${CLAUDE_MD} does not exist — nothing to remove"
    fi

    for kind in agents commands hooks; do
        src_dir="${REPO_ROOT}/claude/${kind}"
        [[ -d "$src_dir" ]] || continue
        for f in "$src_dir"/*; do
            [[ -e "$f" ]] || continue
            rm -f "${CLAUDE_DIR}/${kind}/$(basename "$f")"
        done
    done
    rm -f "${USER_RULES_DIR}"/egor-ai-*.md
    for d in "${REPO_ROOT}"/claude/skills/*/; do
        [[ -d "$d" ]] && rm -rf "${CLAUDE_DIR}/skills/$(basename "$d")"
    done
    rm -f "${CONFIG_DIR}/install.conf"
    [[ -f "$SETTINGS_JSON" ]] && sync_hooks remove
    git -C "$REPO_ROOT" config --unset core.hooksPath 2>/dev/null || true
    ok "Uninstall complete."
    exit 0
fi

echo
say "1/3  Building managed block from claude/rules/ ..."
if ! compgen -G "${RULES_DIR}/*.md" >/dev/null; then
    err "No rule files in ${RULES_DIR} — nothing to install."
    exit 1
fi
for f in "${RULES_DIR}"/*.md; do
    if is_scoped "$f"; then
        say "    - $(basename "$f")  (path-scoped -> ~/.claude/rules/)"
    else
        say "    - $(basename "$f")"
    fi
done

TMP_BLOCK="$(mktemp)"
trap 'rm -f "$TMP_BLOCK"' EXIT
build_block > "$TMP_BLOCK"

if [[ "$DRY_RUN" -eq 1 ]]; then
    echo
    say "--dry-run — block that would be written to ${CLAUDE_MD}:"
    echo
    cat "$TMP_BLOCK"
    exit 0
fi

mkdir -p "$CLAUDE_DIR"
touch "$CLAUDE_MD"
splice "$TMP_BLOCK"
ok "${CLAUDE_MD} synced"

for f in "${RULES_DIR}"/*.md; do
    is_scoped "$f" || continue
    mkdir -p "$USER_RULES_DIR"
    render "$f" > "$(scoped_target "$f")"
done

echo
say "2/3  Installing agents / commands / hooks ..."
installed_any=0
for kind in agents commands hooks; do
    src_dir="${REPO_ROOT}/claude/${kind}"
    [[ -d "$src_dir" ]] || continue
    compgen -G "${src_dir}/*" >/dev/null || continue
    mkdir -p "${CLAUDE_DIR}/${kind}"
    for f in "$src_dir"/*; do
        [[ -f "$f" ]] || continue
        [[ "$(basename "$f")" == "hooks.json" ]] && continue
        cp "$f" "${CLAUDE_DIR}/${kind}/"
        [[ "$kind" == "hooks" ]] && chmod +x "${CLAUDE_DIR}/${kind}/$(basename "$f")"
        say "    - ${kind}/$(basename "$f")"
        installed_any=1
    done
done
for d in "${REPO_ROOT}"/claude/skills/*/; do
    [[ -f "${d}SKILL.md" ]] || continue
    name="$(basename "$d")"
    mkdir -p "${CLAUDE_DIR}/skills/${name}"
    cp -R "${d}". "${CLAUDE_DIR}/skills/${name}/"
    say "    - skills/${name}"
    installed_any=1
done
if [[ "$installed_any" -eq 0 ]]; then
    say "    nothing to install yet (placeholders are empty)"
fi
ok "Payload synced"

if [[ -f "$HOOKS_MANIFEST" ]]; then
    sync_hooks register
fi
if git -C "$REPO_ROOT" rev-parse --git-dir >/dev/null 2>&1 && [[ -d "${REPO_ROOT}/githooks" ]]; then
    git -C "$REPO_ROOT" config core.hooksPath githooks
    say "  git hooks: core.hooksPath -> githooks (rules re-install on commit, pull and checkout)"
fi

echo
say "3/3  Recording install location ..."
mkdir -p "$CONFIG_DIR"
{
    printf 'INSTALL_DIR=%s\n' "$REPO_ROOT"
    printf 'INSTALL_TIMESTAMP=%s\n' "$(date +%s)"
} > "${CONFIG_DIR}/install.conf"
ok "${CONFIG_DIR}/install.conf written"

echo
ok "Install complete. Open a new Claude Code session to pick up the rules."
